    <h3 class="accent" style="margin-bottom:1.5rem;">AC4 : Adopter une attitude professionnelle et déontologique</h3>
    <div class="grille-bilan">
        <div class="cellule-statut statut-non">
            <span class="statut-label statut-label-non">Non Acquis</span>
            <ul class="statut-items">
                <li>Attitude non-professionnelle ou non-respectueuse</li>
                <li>Aucun respect de la confidentialité</li>
                <li>Non-respect du code d'éthique</li>
            </ul>
        </div>
        <div class="cellule-statut statut-cours">
            <span class="statut-label statut-label-cours">En cours d'acquisition</span>
            <ul class="statut-items">
                <li>Attitude généralement professionnelle avec quelques écarts</li>
                <li>Respect basique de la confidentialité</li>
                <li>Quelques manquements éthiques identifiés et corrigés</li>
            </ul>
        </div>
        <div class="cellule-statut statut-acquis">
            <span class="statut-label statut-label-acquis">Acquis</span>
            <ul class="statut-items">
                <li>Attitude professionnelle, respectueuse et courtoise</li>
                <li>Respect absolu de la confidentialité et du secret professionnel</li>
                <li>Comportement éthique et conforme aux valeurs de l'équipe</li>
            </ul>
        </div>
